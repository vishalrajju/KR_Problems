/******************************************************************************
* Name        : htoi()
* Description : convs hexadecimal to integer
* Arguments   : int i , result , digit
* Returns     : <type> – description
******************************************************************************/
int htoi(char s[])
{
    int i = 0;
    int res = 0;
    int digit;
    if (s[0] == '0' && (s[1] == 'x' || s[1] == 'X')) // it eliminates the 0x or 0X
    {
        i = 2;
    }
    while (s[i] != '\0')
    {
        if (s[i] >= '0' && s[i] <= '9')
        {
            digit = s[i] - '0';
        }
        else if (s[i] >= 'a' && s[i] <= 'f')
        {
            digit = s[i] - 'a' + 10;
        }
        else if (s[i] >= 'A' && s[i] <= 'F')
        {
            digit = s[i] - 'A' + 10;
        }
        else
        {
            return -1;
        }
        res = res * 16 + digit;
        i++;
    }
    return res;
}
