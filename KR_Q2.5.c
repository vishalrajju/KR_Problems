/******************************************************************************
* Name        : any()
* Description : checks wheather charac from s2 is present in s1 or not
* Arguments   : int i and int j
* Returns     : <type> – description
******************************************************************************/
int any(char s1[], char s2[])
{
    int i, j;
    for (i = 0; s1[i] != '\0'; i++)
    {
        for (j = 0; s2[j] != '\0'; j++)
        {
            if (s1[i] == s2[j])
            {
                return i;
            }
        }
    }
    return -1;
}
