/******************************************************************************
* Name        : expand()
* Description : 
* Arguments   : <type><name> – description
* Returns     : <type> – description
******************************************************************************/

void expand(char s1[], char s2[])
{
    int i = 0, j = 0;
    char c;
    while (s1[i] != '\0')
    {
        if (s1[i + 1] == '-' && s1[i + 2] != '\0')
        {
            if ((s1[i] >= 'a' && s1[i] <= 'z' &&
                 s1[i + 2] >= 'a' && s1[i + 2] <= 'z') ||

                (s1[i] >= 'A' && s1[i] <= 'Z' &&
                 s1[i + 2] >= 'A' && s1[i + 2] <= 'Z') ||

                (s1[i] >= '0' && s1[i] <= '9' &&
                 s1[i + 2] >= '0' && s1[i + 2] <= '9'))
            {
                if (s1[i] <= s1[i + 2])
                {
                    for (c = s1[i]; c <= s1[i + 2]; c++)
                    {
                        s2[j++] = c;
                    }

                    i += 3;
                }
                else
                {
                    s2[j++] = s1[i++];
                }
            }
            else
            {
                s2[j++] = s1[i++];
            }
        }
        else
        {
            s2[j++] = s1[i++];
        }
    }

    s2[j] = '\0';
}


