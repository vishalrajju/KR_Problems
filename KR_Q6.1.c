int getword(char word[], int lim)
{
    int c, d, i = 0;

    while (isspace(c = getchar()))
        ;

    if (c == EOF)
        return EOF;
    if (c == '#')
    {
        while (c != '\n' && c != EOF)
        {
            if (i < lim - 1)
                word[i++] = c;
            c = getchar();
        }
    }
    
    else if (c == '"')
    {
        word[i++] = c;
        while ((c = getchar()) != '"' && c != EOF)
            if (i < lim - 1) word[i++] = c;
        if (c == '"' && i < lim - 1) word[i++] = c;
    }
    
    else if (c == '/' && ((d = getchar()) == '/' || d == '*'))
    {
        word[i++] = '/';
        word[i++] = d;

        if (d == '/')
        {
            while ((c = getchar()) != '\n' && c != EOF)
                if (i < lim - 1) word[i++] = c;
        }
        else
        {
            while ((c = getchar()) != EOF)
            {
                if (i < lim - 1) word[i++] = c;
                if (c == '*' && (d = getchar()) == '/')
                {
                    if (i < lim - 1) word[i++] = d;
                    break;
                }
                if (d != EOF && c == '*')
                    ungetc(d, stdin);
            }
        }
    }

    else if (isalpha(c) || c == '_')
    {
        do {
            if (i < lim - 1) word[i++] = c;
            c = getchar();
        } while (isalnum(c) || c == '_');

        if (c != EOF)
            ungetc(c, stdin);
    }
    else
        word[i++] = c;

    word[i] = '\0';
    return word[0];
}
