int main()
{
    int fahr;

    for (fahr = 0; fahr <= 300; fahr += 20)
    {
        printf("%d\t%.2f\n", fahr, conv(fahr));
    }
    return 0;
}

/******************************************************************************
* Function Definitions
******************************************************************************/
/******************************************************************************
* Name        : conv()
* Description : converts fhrn to celsius
* Arguments   : int fahr – temp in fahr
* Returns     : float – Converted temperature in Celsius
******************************************************************************/
float conv(int fahr)   
{
    float celsius;
    celsius = (5.0 / 9.0) * (fahr - 32);
    return celsius;
}

