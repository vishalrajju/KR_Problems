 int main()
{
    char s[100];
    char t[50];
    printf("Enter first string: ");
    fgets(s, sizeof(s), stdin);
    printf("Enter second string: ");
    fgets(t, sizeof(t), stdin);
    int i = 0;
    while (s[i] != '\0')
    {
        if (s[i] == '\n')
        {
            s[i] = '\0';
            break;
        }
        i++;
    }
    i = 0;
    while (t[i] != '\0')
    {
        if (t[i] == '\n')
        {
            t[i] = '\0';
            break;
        }
        i++;
    }

    strtcat(s, t);

    printf("Con string: %s\n", s);

    return 0;
}

/******************************************************************************
* Function Definitions
******************************************************************************/
/******************************************************************************
* Name        : strcat()
* Description : It is used to concatenate the strings
* Arguments   : <char *s and the *t> – used to store the value of user's input
* Returns     : <type> – description
******************************************************************************/
void strtcat(char *s, char *t){
    while(*s != '\0'){
        s++;
    }
    while((*s = *t) != '\0'){
        s++;
        t++;
    }
}
