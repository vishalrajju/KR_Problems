#define MAX_LENGTH 10
/******************************************************************************
* Typedefs and Structures
******************************************************************************/

/******************************************************************************
* Global Variables
******************************************************************************/

/******************************************************************************
* Function Prototypes
******************************************************************************/

/******************************************************************************
* Main Function
******************************************************************************/
int main(){
    int wordLengths[MAX_LENGTH] = {0};
    int c;
    int currentLength = 0;
    while((c = getchar()) != EOF){
        if(c == ' ' || c == '\n' || c == '\t'){
            if(currentLength>0 && currentLength<MAX_LENGTH){
                ++wordLengths[currentLength];
            }
            currentLength=0;
        } else{
            ++currentLength;
        }
    }
    if(currentLength>0 && currentLength<MAX_LENGTH){
        ++wordLengths[currentLength];
    }
    for(int i = 1;i<MAX_LENGTH;i++){
        if(wordLengths[i]>0){
            printf("%d:", i);
        }
        for(int j =0;j<wordLengths[i];j++){
            printf("#");
        }
        printf("\n");
    }
    return 0;
}


