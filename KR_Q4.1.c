int strindex(char s[],char t[]){
    int i , j = 0;
    int k = 0;
    int position =-1;
    for(int i =0; s[i] != '\0'; i++){
        j=i;
        k=0;
        while(t[k] != '\0' && s[j] == t[k]){
            j++;
            k++;
        }
        if(t[k] == '\0'){
            return i;
        }
    }
    return position;
}
