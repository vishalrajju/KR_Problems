/******************************************************************************
* Name        : lower()
* Description : it converts the uppercase to lowercase letters
* Arguments   : int c – conv to lowercase
* Returns     : int 
******************************************************************************/
int lower(int c)
{
    return (c >= 'A' && c <= 'Z') ? c + ('a' - 'A') : c;
}
