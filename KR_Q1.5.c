int main()
{
    float fhrn;
    for (int cel = 300; cel >= 0; cel = cel - 20)
    {
        fhrn = (cel * 9.0 / 5.0) + 32;
        printf("%d\t%.2f\n", cel, fhrn);
    }
    return 0;
}


