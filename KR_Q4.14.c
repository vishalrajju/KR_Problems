#include <stdio.h>

/******************************************************************************
* Macros and Constants
******************************************************************************/
#define swap(t, x, y) { \
    t temp;             \
    temp = x;           \
    x = y;              \
    y = temp;           \
}
/******************************************************************************
* Typedefs and Structures
******************************************************************************/

/******************************************************************************
* Global Variables
******************************************************************************/

/******************************************************************************
* Function Prototypes
******************************************************************************/

/******************************************************************************
* Main Function
******************************************************************************/
int main(void)
{
    int a = 10;
    int b = 20;
    printf("Before swapping:\n");
    printf("a = %d, b = %d\n", a, b);
    swap(int, a, b);
    printf("After swapping:\n");
    printf("a = %d, b = %d\n", a, b);
    return 0;
}

