/******************************************************************************
* Name        : reverse(s)
* Description : Brief description of what the function does
* Arguments   : <type><name> – description
* Returns     : <type> – description
******************************************************************************/
void reverse(char s[], int start, int end)
{
    char temp;
    if (start >= end)
        return;
    temp = s[start];
    s[start] = s[end];
    s[end] = temp;
    reverse(s, start + 1, end - 1);
}
