#include <stdio.h>
#include <ctype.h>
/******************************************************************************
* Macros and Constants
******************************************************************************/
#define MAXCHAR 128
/******************************************************************************
* Typedefs and Structures
******************************************************************************/

/******************************************************************************
* Global Variables
******************************************************************************/

/******************************************************************************
* Function Prototypes
******************************************************************************/

/******************************************************************************
* Main Function
******************************************************************************/
int main(void)
{
    int charfreq[MAXCHAR] = {0};
    int c;
    while ((c = getchar()) != EOF) // read  one char at a time and stops when it is EOF
    {
        if (c < MAXCHAR) // count the number of char
        {
            ++charfreq[c];
        }
    }

    for (int i = 0; i < MAXCHAR; ++i)
    {
        if (charfreq[i] != 0 && isprint(i))
        {
            printf(" %c : ", i);

            for (int j = 0; j < charfreq[i]; ++j)
            {
                putchar('*');
            }

            putchar('\n');
        }
        else if (charfreq[i] != 0)
        {
            printf("----");

            for (int j = 0; j < charfreq[i]; ++j)
            {
                putchar('*');
            }

            putchar('\n');
        }
    }

    return 0;
}

