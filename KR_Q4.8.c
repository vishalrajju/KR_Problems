int buf;
int bufp = 0;
/******************************************************************************
* Function Prototypes
******************************************************************************/
int getch(void);
void ungetch(int c);
/******************************************************************************
* Main Function
******************************************************************************/
int main(void)
{
    int c;
    c = getch();
    ungetch(c);
    c = getch();
    printf("Character = %c\n", c);
    return 0;
}
/******************************************************************************
* Function Definitions
******************************************************************************/
/******************************************************************************
* Name        : FunctionName
* Description : Brief description of what the function does
* Arguments   : <type><name> – description
* Returns     : <type> – description
******************************************************************************/
int getch(void)
{
    if (bufp > 0)
    {
        bufp = 0;
        return buf;
    }
    return getchar();
}
void ungetch(int c)
{
    if (bufp > 0)
        printf("Error: buffer is full\n");
    else
    {
        buf = c;
        bufp = 1;
    }
}

