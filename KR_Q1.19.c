#include <stdio.h>
#include <string.h>
/******************************************************************************
* Macros and Constants
******************************************************************************/
#define MAX 1000
/******************************************************************************
* Typedefs and Structures
******************************************************************************/

/******************************************************************************
* Global Variables
******************************************************************************/

/******************************************************************************
* Function Prototypes
******************************************************************************/
void reverse(char s[]);
/******************************************************************************
* Main Function
******************************************************************************/
int main(void)
{
    char s[MAX];
    int i, c;
    i = 0;
    while ((c = getchar()) != EOF)
    {
        if (c == '\n')
        {
            s[i] = '\0';

            reverse(s);

            printf("%s\n", s);

            i = 0;
        }
        else if (i < MAX - 1)
        {
            s[i] = c;
            ++i;
        }
    }
    if (i > 0)
    {
        s[i] = '\0';
        reverse(s);
        printf("%s\n", s);
    }
    return 0;
}
/******************************************************************************
* Function Definitions
******************************************************************************/
/******************************************************************************
* Name        : reverse()
* Description : used to reverse the string
* Arguments   : int i , j
* Returns     : <type> – description
******************************************************************************/
void reverse(char s[])
{
    int i, j;
    char temp;
    i = 0;
    j = strlen(s) - 1;
    while (i < j)
    {
        temp = s[i]; // saves s[i] temporarily in temp
        s[i] = s[j]; // moves right charac to the left side
        s[j] = temp; // now the temp replaces with the s[j]
        ++i;
        --j;
    }
}
