int main(void)
{
    int i = 0;
    int c;
    int lim = 10;
    char s[10];

    while (i < lim - 1)
    {
        c = getchar();

        if (c == '\n')
            break;

        if (c == EOF)
            break;

        s[i] = c;
        ++i;
    }

    s[i] = '\0';

    printf("String: %s\n", s);

    return 0;
}


