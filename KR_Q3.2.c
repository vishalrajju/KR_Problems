void escape(char s[], char t[])
{
    int i, j;

    i = 0;
    j = 0;

    while (t[i] != '\0')
    {
        switch (t[i])
        {
            case '\n':
                s[j++] = '\\';
                s[j++] = 'n';
                break;
            case '\t':
                s[j++] = '\\';
                s[j++] = 't';
                break;
            default:
                s[j++] = t[i];
                break;
        }
        i++;
    }

    s[j] = '\0';
}
void unescape(char s[], char t[])
{
    int i, j;

    i = 0;
    j = 0;
    while (t[i] != '\0')
    {
        if (t[i] == '\\' && t[i + 1] != '\0')
        {
            i++;
            switch (t[i])
            {
                case 'n':
                    s[j++] = '\n';
                    break;

                case 't':
                    s[j++] = '\t';
                    break;

                default:
                    s[j++] = '\\';
                    s[j++] = t[i];
                    break;
            }
        }
        else
        {
            s[j++] = t[i];
        }
        i++;
    }

    s[j] = '\0';
}

