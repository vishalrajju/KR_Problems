void escape(char s[], char t[]);
void unescape(char s[], char t[]);
/******************************************************************************
* Main Function
******************************************************************************/
int main()
{
    char t[] = "A\nB";
    char s[100];
    escape(s, t);
    printf("After escape: %s\n", s);
    unescape(s, "AB\tC");
    printf("Aft unescape:\n%s\n", s);
    return 0;
}
