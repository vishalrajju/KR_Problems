/******************************************************************************
* Name        : squeeze()
* Description : remove the req charac from the input
* Arguments   : <type><name> – description
* Returns     : <type> – description
******************************************************************************/
void squeeze(char s1[], char s2[])
{
    int i, j, k;
    for (i = 0; s1[i] != '\0'; i++)
    {
        for (j = 0; s2[j] != '\0'; j++)
        {
            if (s1[i] == s2[j])
            {
                break;
            }
        }

        if (s2[j] == '\0')
        {
            s1[k] = s1[i];
            k++;
        }
    }
    s1[k] = '\0';
}
