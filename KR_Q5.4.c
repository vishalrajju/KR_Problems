int strend(char *s, char *t)
{
    char *s_end = s;
    char *t_end = t;
    while (*s_end != '\0')
        s_end++;
    while (*t_end != '\0')
        t_end++;
    while (t_end > t)
    {
        if (*--s_end != *--t_end)
            return 0;
    }
    return 1;
}
