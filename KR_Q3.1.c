int main()
{
    int v[] = {8, 25, 56, 61, 67, 73, 85};
    int n = sizeof(v) / sizeof(v[0]);
    int x = 67;

    int result = binsearch(x, v, n);

    if (result != -1)
        printf("Element found at index %d\n", result);
    else
        printf("Element not found\n");

    return 0;
}
